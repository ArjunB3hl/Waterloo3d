def area_class(layer, cls):
    c = cls.split('/')[-1]
    key = (layer, c)
    if key not in _AREA and layer == 'water': key = ('water', '*')
    if key not in _AREA: return None
    g, pr = _AREA[key]
    return g, CLS[g], pr


def road_style(r):
    if r['kind'] == 'rail':
        return {'ground': 'rail', 'z': 5, 'casing': None}
    c = r['cls']
    if c in ('motorway', 'trunk', 'primary', 'secondary'):
        return {'ground': 'major_road', 'z': 4, 'casing': (86, 88, 92)}
    if c in ('tertiary', 'residential', 'unclassified', 'living_street', 'unknown'):
        return {'ground': 'road', 'z': 3, 'casing': (104, 106, 110)}
    if c == 'service':
        return {'ground': 'road', 'z': 2, 'casing': None}
    if c in ('footway', 'path', 'cycleway', 'steps', 'track', 'bridleway', 'pedestrian'):
        return {'ground': 'path', 'z': 1, 'casing': None}
    return None
